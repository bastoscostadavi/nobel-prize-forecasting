def norm(name: str) -> str:
    s = unicodedata.normalize("NFKD", name).encode("ascii", "ignore").decode().casefold()
    return "".join(ch for ch in s if ch.isalnum())


# ---------------------------------------------------------------- sources
SOURCES: dict[str, dict] = {}


def wiki(title: str) -> str:
    sid = "wp_" + norm(title)[:40]
    SOURCES[sid] = {
        "title": f"Wikipedia: {title}",
        "url": "https://en.wikipedia.org/wiki/" + title.replace(" ", "_"),
        "accessed_on": ACCESSED,
        "source_type": "encyclopedia_overview",
    }
    return sid


def wikidata(qid: str, label: str) -> str:
    sid = "wd_" + qid
    SOURCES[sid] = {
        "title": f"Wikidata: {label}",
        "url": f"https://www.wikidata.org/wiki/{qid}",
        "accessed_on": ACCESSED,
        "source_type": "registry_living_status",
    }
    return sid


