def hist(name: str, contribution: str, extra_sources: list[str] | None = None) -> dict:
    date, qid, wp = DEATHS.get(name, (None, None, None))
    sids = list(extra_sources or [])
    if qid:
        sids.append(wikidata(qid, f"{name} (date of death {date})"))
    elif wp:
        sids.append(wiki(wp))
    return {
        "name": name,
        "contribution": contribution,
        "death_date": date,
        "source_ids": sids,
        "eligible_credit_pool": False,
    }


